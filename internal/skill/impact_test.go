func TestImpactFormattingAndPartitioning(t *testing.T) {
	root := t.TempDir()

	// Write mock files so isFileHeaderGenerated can inspect if needed
	files := map[string]string{
		"internal/engine/app.go":                     "package engine\nfunc (a *Engine) SendMessage() {}\n",
		"internal/engine/stream_delivery_test.go":   "package engine\n",
		"internal/engine/failed_turn_test.go":       "package engine\n",
		"internal/engine/rpc/server_gen.go":         "// Code generated by gen. DO NOT EDIT.\npackage rpc\n",
		"internal/engine/rpc/client_gen.go":         "// Code generated by gen. DO NOT EDIT.\npackage rpc\n",
		"internal/engine/api_gen.go":                "// Code generated by gen. DO NOT EDIT.\npackage engine\n",
		"internal/engine/regenerate.go":             "package engine\n",
		"internal/engine/testdata/sample.json":      "{}\n",
	}
	for rel, body := range files {
		abs := filepath.Join(root, rel)
		_ = os.MkdirAll(filepath.Dir(abs), 0o755)
		_ = os.WriteFile(abs, []byte(body), 0o644)
	}

	info := &lsp.SymbolInfo{
		DefPath: filepath.Join(root, "internal/engine/app.go"),
		DefLine: 2478,
		Hover:   "func (a *Engine) SendMessage(text, to string) (TurnReply, error)",
		Refs: []lsp.Location{
			{Path: filepath.Join(root, "internal/engine/regenerate.go"), Line: 70},
			{Path: filepath.Join(root, "internal/engine/stream_delivery_test.go"), Line: 67},
			{Path: filepath.Join(root, "internal/engine/failed_turn_test.go"), Line: 138},
			{Path: filepath.Join(root, "internal/engine/rpc/server_gen.go"), Line: 1426},
			{Path: filepath.Join(root, "internal/engine/rpc/client_gen.go"), Line: 1811},
			{Path: filepath.Join(root, "internal/engine/api_gen.go"), Line: 292},
			{Path: filepath.Join(root, "internal/engine/testdata/sample.json"), Line: 2},
		},
	}

	formatted := formatImpact(root, "SendMessage", "internal/engine/app.go", info)

	// Verify Header & Declaration
	if !strings.Contains(formatted, "Impact: engine.Engine.SendMessage") {
		t.Errorf("want 'Impact: engine.Engine.SendMessage', got:\n%s", formatted)
	}
	if !strings.Contains(formatted, "Declared at internal/engine/app.go:2478") {
		t.Errorf("want 'Declared at internal/engine/app.go:2478', got:\n%s", formatted)
	}

	// Verify Production references
	if !strings.Contains(formatted, "Production references (1)\n- internal/engine/regenerate.go:70") {
		t.Errorf("want production reference internal/engine/regenerate.go:70, got:\n%s", formatted)
	}

	// Verify Test references
	if !strings.Contains(formatted, "Test references (2)\n- internal/engine/stream_delivery_test.go:67\n- internal/engine/failed_turn_test.go:138") {
		t.Errorf("want test references stream_delivery and failed_turn, got:\n%s", formatted)
	}

	// Verify Other references (generated + testdata)
	if !strings.Contains(formatted, "Other references (4)") {
		t.Errorf("want 4 other references, got:\n%s", formatted)
	}
	if !strings.Contains(formatted, "- internal/engine/rpc/server_gen.go:1426") ||
		!strings.Contains(formatted, "- internal/engine/rpc/client_gen.go:1811") ||
		!strings.Contains(formatted, "- internal/engine/api_gen.go:292") ||
		!strings.Contains(formatted, "- internal/engine/testdata/sample.json:2") {
		t.Errorf("missing expected other references, got:\n%s", formatted)
	}

	// Verify Generated/RPC surface evidence
	if !strings.Contains(formatted, "Generated/RPC surface evidence\n- internal/engine/rpc/server_gen.go:1426\n- internal/engine/rpc/client_gen.go:1811\n- internal/engine/api_gen.go:292") {
		t.Errorf("missing expected generated/RPC surface evidence, got:\n%s", formatted)
	}

	// Verify Related narrow checks
	if !strings.Contains(formatted, "Related narrow checks") {
		t.Errorf("missing Related narrow checks, got:\n%s", formatted)
	}
	if !strings.Contains(formatted, "- internal/engine/failed_turn_test.go") ||
		!strings.Contains(formatted, "- internal/engine/stream_delivery_test.go") {
		t.Errorf("related test files missing, got:\n%s", formatted)
	}
	if !strings.Contains(formatted, "- go test ./internal/engine/...") {
		t.Errorf("want package-level test command 'go test ./internal/engine/...', got:\n%s", formatted)
	}
}

