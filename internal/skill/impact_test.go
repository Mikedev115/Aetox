func TestCodebasePackDispatchesImpactAndNarrows(t *testing.T) {
	root := t.TempDir()
	registry := NewDefaultRegistry(RegistryOptions{SandboxRoot: root})

	// Check codebase pack contains impact
	cbSkill, ok := registry.Get("codebase")
	if !ok {
		t.Fatal("codebase tool is not registered")
	}
	packed, ok := cbSkill.(Packed)
	if !ok {
		t.Fatal("codebase skill does not implement Packed")
	}

	actions := packed.Actions()
	var hasImpact bool
	for _, a := range actions {
		if a == "impact" {
			hasImpact = true
			break
		}
	}
	if !hasImpact {
		t.Errorf("codebase actions %v does not include 'impact'", actions)
	}

	// PackForAction resolution
	toolName, action, perm, found := PackForAction("impact")
	if !found || toolName != "codebase" || action != "impact" || perm != "impact" {
		t.Errorf("PackForAction(impact) = (%s, %s, %s, %v), want (codebase, impact, impact, true)",
			toolName, action, perm, found)
	}

	// Unpack resolution
	if got := Unpack("codebase", map[string]any{"action": "impact"}); got != "impact" {
		t.Errorf("Unpack(codebase, action=impact) = %q, want impact", got)
	}

	// Category check
	if cat := CategoryOf("impact"); cat != CategoryCode {
		t.Errorf("CategoryOf(impact) = %q, want CategoryCode", cat)
	}

	// Narrowing: caller only gets 'impact'
	narrowed := packed.Narrow([]string{"impact"})
	tool := narrowed.(Tool)
	def := tool.ToolDefinition()
	var schema map[string]any
	schemaStr, _ := json.Marshal(def.Function.Parameters)
	_ = json.Unmarshal(schemaStr, &schema)

	props, _ := schema["properties"].(map[string]any)
	if _, hasName := props["name"]; !hasName {
		t.Error("a narrowed codebase holding only 'impact' must still include 'name' in its schema")
	}

	// Call action=symbol on narrowed tool holding only impact -> must be refused
	_, err := tool.ExecuteTool(context.Background(), map[string]any{
		"action": "symbol",
		"path":   "main.go",
		"name":   "main",
	})
	if err == nil || !strings.Contains(err.Error(), "not available here") {
		t.Errorf("expected 'not available here' refusal for symbol on narrowed impact, got: %v", err)
	}
}

