func TestImpactRPCConventionVsConfirmedGenerated(t *testing.T) {
	root := t.TempDir()

	// Write files
	files := map[string]string{
		"internal/engine/rpc/server_gen.go": "// Code generated by protoc-gen-go. DO NOT EDIT.\npackage rpc\n",
		"internal/engine/rpc/handler.go":    "package rpc\n",
		"internal/engine/rpc/rpc_test.go":   "package rpc\n",
	}
	for rel, body := range files {
		abs := filepath.Join(root, rel)
		_ = os.MkdirAll(filepath.Dir(abs), 0o755)
		_ = os.WriteFile(abs, []byte(body), 0o644)
	}

	info := &lsp.SymbolInfo{
		DefPath: filepath.Join(root, "internal/engine/rpc/handler.go"),
		DefLine: 12,
		Hover:   "func HandleCall()",
		Refs: []lsp.Location{
			{Path: filepath.Join(root, "internal/engine/rpc/server_gen.go"), Line: 100},
			{Path: filepath.Join(root, "internal/engine/rpc/handler.go"), Line: 50},
			{Path: filepath.Join(root, "internal/engine/rpc/rpc_test.go"), Line: 25},
		},
	}

	out := formatImpact(root, "HandleCall", "internal/engine/rpc/handler.go", info)

	// handler.go:50 must be a PRODUCTION reference, NOT banished to other!
	if !strings.Contains(out, "Production references (1)\n- internal/engine/rpc/handler.go:50") {
		t.Errorf("handler.go:50 must be classified as a Production reference, got:\n%s", out)
	}

	// server_gen.go:100 is confirmed generated, so it's in other
	if !strings.Contains(out, "Other references (1)\n- internal/engine/rpc/server_gen.go:100") {
		t.Errorf("server_gen.go:100 must be in Other references, got:\n%s", out)
	}

	// rpc_test.go:25 is in tests
	if !strings.Contains(out, "Test references (1)\n- internal/engine/rpc/rpc_test.go:25") {
		t.Errorf("rpc_test.go:25 must be in Test references, got:\n%s", out)
	}

	// Generated/RPC surface evidence:
	// - server_gen.go is confirmed generated (no path convention tag)
	// - handler.go:50 is labeled as path convention only!
	if !strings.Contains(out, "- internal/engine/rpc/server_gen.go:100\n") {
		t.Errorf("server_gen.go:100 should be listed as confirmed generated evidence, got:\n%s", out)
	}
	if !strings.Contains(out, "- internal/engine/rpc/handler.go:50 (path convention only, unconfirmed runtime boundary)") {
		t.Errorf("handler.go:50 must be tagged as path convention only, got:\n%s", out)
	}
}

