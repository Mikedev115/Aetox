package main

// The wire's two generated halves (§248 phase 2): the client, one method per
// API method so *rpc.Client satisfies engine.API the way *Engine does, and
// the server's dispatch table, one case per method that decodes positional
// params and calls the engine. Both are written from the same method list
// the interface and the forwarders come from, so a binding that exists in
// one process exists across the socket, with the same name and the same
// shape, and the currency test catches the one that does not.

import (
	"go/ast"
	"go/format"
	"go/token"
	"strings"
)

// shape is what a method answers with, as the wire carries it: the values
// before a trailing error, and whether there is one.
type shape struct {
	values []ast.Expr
	hasErr bool
}

func shapeOf(fset *token.FileSet, results []ast.Expr) shape {
	s := shape{values: results}
	if n := len(results); n > 0 && exprString(fset, results[n-1]) == "error" {
		s.hasErr = true
		s.values = results[:n-1]
	}
	return s
}

func renderClient(fset *token.FileSet, methods []method, types map[string]bool, imports map[string]string) ([]byte, error) {
	used := map[string]bool{}
	var body strings.Builder
	for _, m := range methods {
		sh := shapeOf(fset, m.results)
		body.WriteString("func (c *Client) " + m.name + "(")
		var args []string
		for i, p := range m.params {
			if i > 0 {
				body.WriteString(", ")
			}
			body.WriteString(p.name + " " + qualify(fset, p.typ, types, used))
			args = append(args, p.name)
		}
		body.WriteString(")")
		body.WriteString(resultsString(fset, m.results, types, used))
		body.WriteString(" {\n")
		var outs []string
		for i, v := range sh.values {
			name := "out" + itoa(i)
			body.WriteString("\tvar " + name + " " + qualify(fset, v, types, used) + "\n")
			outs = append(outs, name)
		}
		params := "nil"
		if len(args) > 0 {
			params = "[]any{" + strings.Join(args, ", ") + "}"
		}
		call := ""
		switch len(outs) {
		case 0:
			call = "c.call(" + quote(m.name) + ", " + params + ", nil)"
		case 1:
			call = "c.call(" + quote(m.name) + ", " + params + ", &" + outs[0] + ")"
		default:
			refs := make([]string, len(outs))
			for i, o := range outs {
				refs[i] = "&" + o
			}
			call = "c.callN(" + quote(m.name) + ", " + params + ", " + strings.Join(refs, ", ") + ")"
		}
		switch {
		case sh.hasErr && len(outs) == 0:
			body.WriteString("\treturn " + call + "\n")
		case sh.hasErr:
			body.WriteString("\terr := " + call + "\n")
			body.WriteString("\treturn " + strings.Join(outs, ", ") + ", err\n")
		default:
			// No error in the signature: a transport failure has nowhere to
			// go but the client's failure hook, and the caller gets the zero
			// value — the way a Wails binding that panicked answers today.
			body.WriteString("\tif err := " + call + "; err != nil {\n")
			body.WriteString("\t\tc.failed(" + quote(m.name) + ", err)\n\t}\n")
			if len(outs) > 0 {
				body.WriteString("\treturn " + strings.Join(outs, ", ") + "\n")
			}
		}
		body.WriteString("}\n\n")
	}

	var b strings.Builder
	b.WriteString("// Code generated by internal/engine/gen. DO NOT EDIT.\n\npackage rpc\n\n")
	b.WriteString("// The screen's end of every engine binding (§248 phase 2): *Client is\n")
	b.WriteString("// engine.API over the wire. A method with no error in its signature\n")
	b.WriteString("// answers its zero value when the wire fails and tells the failure hook.\n\n")
	block, err := importBlock(used, imports, true)
	if err != nil {
		return nil, err
	}
	b.WriteString(block)
	b.WriteString(body.String())
	b.WriteString("var _ engine.API = (*Client)(nil)\n")
	return format.Source([]byte(b.String()))
}

func renderServer(fset *token.FileSet, methods []method, types map[string]bool, imports map[string]string) ([]byte, error) {
	used := map[string]bool{"engine": true}
	var body strings.Builder
	body.WriteString("// dispatch answers one binding call on the engine. ok is false for a\n")
	body.WriteString("// method that is not a binding, so the caller can try its own first.\n")
	body.WriteString("func dispatch(e *engine.Engine, method string, params json.RawMessage) (result any, err error, ok bool) {\n")
	body.WriteString("\tswitch method {\n")
	for _, m := range methods {
		sh := shapeOf(fset, m.results)
		body.WriteString("\tcase " + quote(m.name) + ":\n")
		var refs, args []string
		for i, p := range m.params {
			name := "p" + itoa(i)
			typ := p.typ
			if ell, ok := typ.(*ast.Ellipsis); ok {
				typ = &ast.ArrayType{Elt: ell.Elt}
			}
			body.WriteString("\t\tvar " + name + " " + qualify(fset, typ, types, used) + "\n")
			refs = append(refs, "&"+name)
			if _, ok := p.typ.(*ast.Ellipsis); ok {
				name += "..."
			}
			args = append(args, name)
		}
		if len(refs) > 0 {
			body.WriteString("\t\tif err := decodeParams(params, " + strings.Join(refs, ", ") + "); err != nil {\n")
			body.WriteString("\t\t\treturn nil, err, true\n\t\t}\n")
		}
		call := "e." + m.name + "(" + strings.Join(args, ", ") + ")"
		var rs []string
		for i := range sh.values {
			rs = append(rs, "r"+itoa(i))
		}
		switch {
		case len(sh.values) == 0 && !sh.hasErr:
			body.WriteString("\t\t" + call + "\n\t\treturn nil, nil, true\n")
		case len(sh.values) == 0 && sh.hasErr:
			body.WriteString("\t\treturn nil, " + call + ", true\n")
		case len(sh.values) == 1 && !sh.hasErr:
			body.WriteString("\t\treturn " + call + ", nil, true\n")
		case len(sh.values) == 1 && sh.hasErr:
			body.WriteString("\t\tr0, err := " + call + "\n\t\treturn r0, err, true\n")
		case !sh.hasErr:
			body.WriteString("\t\t" + strings.Join(rs, ", ") + " := " + call + "\n")
			body.WriteString("\t\treturn []any{" + strings.Join(rs, ", ") + "}, nil, true\n")
		default:
			body.WriteString("\t\t" + strings.Join(rs, ", ") + ", err := " + call + "\n")
			body.WriteString("\t\treturn []any{" + strings.Join(rs, ", ") + "}, err, true\n")
		}
	}
	body.WriteString("\t}\n\treturn nil, nil, false\n}\n")

	var b strings.Builder
	b.WriteString("// Code generated by internal/engine/gen. DO NOT EDIT.\n\npackage rpc\n\n")
	b.WriteString("// The engine's end of every binding (§248 phase 2): positional params in,\n")
	b.WriteString("// the method's own answer out, exactly as the forwarder would have called it.\n\n")
	block, err := importBlock(used, imports, true)
	if err != nil {
		return nil, err
	}
	// encoding/json is the server's own import, not one the signatures mention.
	block = strings.Replace(block, "import (\n", "import (\n\t\"encoding/json\"\n\n", 1)
	b.WriteString(block)
	b.WriteString(body.String())
	return format.Source([]byte(b.String()))
}

func quote(s string) string { return "\"" + s + "\"" }

func itoa(i int) string {
	if i == 0 {
		return "0"
	}
	var b []byte
	for i > 0 {
		b = append([]byte{byte('0' + i%10)}, b...)
		i /= 10
	}
	return string(b)
}
